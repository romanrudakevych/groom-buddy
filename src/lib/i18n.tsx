type I18nContextValue = {
  lang: UiLanguage;
  setLang: (lang: UiLanguage) => void;
  t: (key: TranslationKey) => string;
  tr: (value: string | null | undefined) => string;
  dateLocale: string;
};

const I18nContext: React.Context<I18nContextValue | null> =
  ((globalThis as Record<string, unknown>)["__crmI18nContext"] as React.Context<I18nContextValue | null>) ??
  ((globalThis as Record<string, unknown>)["__crmI18nContext"] = createContext<I18nContextValue | null>(null));

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<UiLanguage>("ru");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "ru" || stored === "cs") setLangState(stored);
  }, []);

  const setLang = (next: UiLanguage) => {
    setLangState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18nContextValue>(
    () => ({
      lang,
      setLang,
      t: (key) => strings[lang][key],
      tr: (valueToTranslate) => {
        if (!valueToTranslate) return "";
        return valueTranslations[valueToTranslate]?.[lang] ?? valueToTranslate;
      },
      dateLocale: lang === "ru" ? "ru-RU" : "cs-CZ",
    }),
    [lang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}

export function localizedOptions(values: readonly string[], tr: (value: string) => string) {
  return values.map((value) => ({ value, label: tr(value) }));
}

export function translatedServiceNames(
  data: { services: { id: string; name: string }[] },
  ids: string[],
  tr: (value: string) => string,
) {
  return ids
    .map((id) => data.services.find((service) => service.id === id)?.name)
    .filter((name): name is string => Boolean(name))
    .map((name) => tr(name))
    .join(", ");
}